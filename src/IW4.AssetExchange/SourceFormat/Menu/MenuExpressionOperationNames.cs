    public static string Get(OperationEnum operation)
    {
        int index = (int)operation;
        if ((uint)index >= (uint)Names.Length || !Enum.IsDefined(operation))
        {
            throw new InvalidDataException(
                $"Unsupported PS3 Menu expression opcode 0x{index:X}.");
        }

        return Names[index];
    }
