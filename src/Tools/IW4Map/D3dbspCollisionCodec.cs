    public static byte[] EncodeCollisionBorders(IReadOnlyList<CollisionBorder> borders)
    {
        ArgumentNullException.ThrowIfNull(borders);
        var data = new byte[checked(borders.Count * DiskCollisionBorderSize)];
        for (int index = 0; index < borders.Count; index++)
        {
            CollisionBorder border = borders[index] ??
                throw new InvalidDataException($"Collision border row {index} is null.");
            if (border.DistEq.Count != 3)
            {
                throw new InvalidDataException(
                    $"Collision border row {index} has {border.DistEq.Count} distance-equation values; expected 3.");
            }

            Span<byte> row = data.AsSpan(
                index * DiskCollisionBorderSize,
                DiskCollisionBorderSize);
            WriteSingle(row, 0, border.DistEq[0]);
            WriteSingle(row, 4, border.DistEq[1]);
            WriteSingle(row, 8, border.DistEq[2]);
            WriteSingle(row, 12, border.ZBase);
            WriteSingle(row, 16, border.ZSlope);
            WriteSingle(row, 20, border.Start);
            WriteSingle(row, 24, border.Length);
        }

        return data;
    }

    public static byte[] EncodeCollisionAabbs(IReadOnlyList<CollisionAabbTree> aabbTrees)
    {
        ArgumentNullException.ThrowIfNull(aabbTrees);
        var data = new byte[checked(aabbTrees.Count * DiskCollisionAabbSize)];
        for (int index = 0; index < aabbTrees.Count; index++)
        {
            CollisionAabbTree tree = aabbTrees[index] ??
                throw new InvalidDataException($"Collision AABB row {index} is null.");
            Span<byte> row = data.AsSpan(
                index * DiskCollisionAabbSize,
                DiskCollisionAabbSize);
            WriteVec3(row, 0, tree.Origin);
            WriteVec3(row, 12, tree.HalfSize);
            BinaryPrimitives.WriteUInt16LittleEndian(row[24..], tree.MaterialIndex);
            BinaryPrimitives.WriteUInt16LittleEndian(row[26..], tree.ChildCount);
            BinaryPrimitives.WriteInt32LittleEndian(row[28..], tree.FirstChildOrPartitionIndex);
        }

        return data;
    }

    private static byte[] EncodeBytes(IReadOnlyList<byte> values)
    {
        ArgumentNullException.ThrowIfNull(values);
        var data = new byte[values.Count];
        for (int index = 0; index < values.Count; index++)
            data[index] = values[index];

        return data;
    }

    private static int GetElementCount(ReadOnlySpan<byte> data, int elementSize, string description)
    {
        if (data.Length % elementSize != 0)
        {
            throw new InvalidDataException(
                $"The {description} lump length {data.Length} is not divisible by {elementSize}.");
        }

        return data.Length / elementSize;
    }

    private static short ReadInt16Checked(
        ReadOnlySpan<byte> row,
        int offset,
        int nodeIndex,
        int childIndex)
    {
        int value = BinaryPrimitives.ReadInt32LittleEndian(row[offset..]);
        if (value is < short.MinValue or > short.MaxValue)
        {
            throw new InvalidDataException(
                $"Collision node row {nodeIndex} child {childIndex} value {value} exceeds the IW4 short range.");
        }

        return (short)value;
    }

    private static void ValidateMaterialIndex(int index, int count, string description)
    {
        if ((uint)index >= (uint)count)
        {
            throw new InvalidDataException(
                $"{description} references material {index}; the material table has {count} rows.");
        }
    }

    private static byte ToByteOffset(int value, int brushIndex, string description)
    {
        if ((uint)value > byte.MaxValue)
        {
            throw new InvalidDataException(
                $"Collision brush row {brushIndex} {description} adjacency offset {value} exceeds the IW4 byte range.");
        }

        return (byte)value;
    }

    private static void AdvanceEdges(
        int totalEdgeCount,
        int count,
        int brushIndex,
        ref int edgeIndex,
        ref int brushEdgeOffset)
    {
        if (edgeIndex > totalEdgeCount - count)
        {
            throw new InvalidDataException(
                $"Collision brush row {brushIndex} consumes past the {totalEdgeCount}-byte adjacency table.");
        }

        edgeIndex += count;
        brushEdgeOffset = checked(brushEdgeOffset + count);
    }

    private static Bounds DecodeBounds(IReadOnlyList<float> mins, IReadOnlyList<float> maxs)
    {
        Vec3 midpoint = new()
        {
            X = Average(mins[0], maxs[0]),
            Y = Average(mins[1], maxs[1]),
            Z = Average(mins[2], maxs[2])
        };
        return new Bounds
        {
            MidPoint = midpoint,
            // IW4 derives half-size from the rounded midpoint rather than from
            // an independently rounded half-difference.
            HalfSize = new Vec3
            {
                X = midpoint.X - mins[0],
                Y = midpoint.Y - mins[1],
                Z = midpoint.Z - mins[2]
            }
        };
    }

    // Round the computed midpoint once, after averaging the two disk floats.
    private static float Average(float left, float right) =>
        (float)(((double)left + right) * 0.5);

    private static Vec3 ReadVec3(ReadOnlySpan<byte> row, int offset) => new()
    {
        X = ReadSingle(row, offset),
        Y = ReadSingle(row, offset + 4),
        Z = ReadSingle(row, offset + 8)
    };

    private static float ReadSingle(ReadOnlySpan<byte> row, int offset) =>
        BitConverter.Int32BitsToSingle(BinaryPrimitives.ReadInt32LittleEndian(row[offset..]));

    private static void WriteVec3(Span<byte> row, int offset, Vec3 value)
    {
        WriteSingle(row, offset, value.X);
        WriteSingle(row, offset + 4, value.Y);
        WriteSingle(row, offset + 8, value.Z);
    }

    private static void WriteSingle(Span<byte> row, int offset, float value) =>
        BinaryPrimitives.WriteInt32LittleEndian(row[offset..], BitConverter.SingleToInt32Bits(value));
}
