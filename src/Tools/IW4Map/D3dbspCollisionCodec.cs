namespace IW4Map;

internal static class D3dbspCollisionCodec
{
    private const int DiskPlaneSize = 16;
    private const int DiskNodeSize = 36;
    private const int DiskBrushSize = 4;
    private const int DiskBrushSideSize = 8;
    private const int DiskLeafBrushSize = 4;
    private const int DiskLeafSurfaceSize = 4;
    private const int DiskCollisionVertSize = 12;
    private const int DiskCollisionIndexSize = 2;
    private const int DiskCollisionBorderSize = 28;
    private const int DiskCollisionAabbSize = 32;
    private const int DiskMaterialSize = 72;

    public static IReadOnlyList<CPlane> DecodePlanes(ReadOnlySpan<byte> data)
    {
        int count = GetElementCount(data, DiskPlaneSize, "collision plane");
        var planes = new CPlane[count];
        for (int index = 0; index < planes.Length; index++)
        {
            ReadOnlySpan<byte> row = data.Slice(index * DiskPlaneSize, DiskPlaneSize);
            Vec3 normal = ReadVec3(row, 0);
            planes[index] = new CPlane
            {
                Normal = normal,
                Dist = ReadSingle(row, 12),
                Type = normal.X == 1.0f
                    ? (byte)0
                    : normal.Y == 1.0f
                        ? (byte)1
                        : normal.Z == 1.0f
                            ? (byte)2
                            : (byte)3,
                // Stock IW4 map fastfiles serialize this byte as zero. It is not
                // the sign mask generated by the IW3 collision loader.
                SignBits = 0,
                Pad12 = new byte[2]
            };
        }

        return Array.AsReadOnly(planes);
    }

    public static IReadOnlyList<CNode> DecodeNodes(
        ReadOnlySpan<byte> data,
        IReadOnlyList<CPlane> planes)
    {
        ArgumentNullException.ThrowIfNull(planes);
        int count = GetElementCount(data, DiskNodeSize, "collision node");
        var nodes = new CNode[count];
        for (int index = 0; index < nodes.Length; index++)
        {
            ReadOnlySpan<byte> row = data.Slice(index * DiskNodeSize, DiskNodeSize);
            int planeIndex = BinaryPrimitives.ReadInt32LittleEndian(row);
            if ((uint)planeIndex >= (uint)planes.Count)
            {
                throw new InvalidDataException(
                    $"Collision node row {index} references plane {planeIndex}; the plane table has {planes.Count} rows.");
            }

            nodes[index] = new CNode
            {
                Plane = planes[planeIndex],
                Children = new[]
                {
                    ReadInt16Checked(row, 4, index, 0),
                    ReadInt16Checked(row, 8, index, 1)
                }
            };
        }

        return Array.AsReadOnly(nodes);
    }

    public static IReadOnlyList<ClipMaterial> DecodeMaterials(ReadOnlySpan<byte> data)
    {
        int count = GetElementCount(data, DiskMaterialSize, "collision material");
        var materials = new ClipMaterial[count];
        for (int index = 0; index < materials.Length; index++)
        {
            ReadOnlySpan<byte> row = data.Slice(index * DiskMaterialSize, DiskMaterialSize);
            int nameLength = row[..64].IndexOf((byte)0);
            if (nameLength < 0)
            {
                throw new InvalidDataException(
                    $"Collision material row {index} has no terminator in its 64-byte name field.");
            }

            materials[index] = new ClipMaterial
            {
                Name = Encoding.Latin1.GetString(row[..nameLength]),
                SurfaceFlags = BinaryPrimitives.ReadInt32LittleEndian(row[64..]),
                // IW4 retains the disk contents flags. The IW3 runtime loader's
                // 0xDFFFFFFB mask is not part of the IW4 linked asset graph.
                Contents = BinaryPrimitives.ReadInt32LittleEndian(row[68..])
            };
        }

        return Array.AsReadOnly(materials);
    }

    public static IReadOnlyList<byte> DecodeBrushEdges(ReadOnlySpan<byte> data) =>
        Array.AsReadOnly(data.ToArray());

    public static (
        IReadOnlyList<CBrushSide> BrushSides,
        IReadOnlyList<CBrush> Brushes,
        IReadOnlyList<Bounds> BrushBounds,
        IReadOnlyList<uint> BrushContents) DecodeBrushes(
            ReadOnlySpan<byte> diskBrushes,
            ReadOnlySpan<byte> diskBrushSides,
            ReadOnlySpan<byte> diskSideEdgeCounts,
            IReadOnlyList<byte> brushEdges,
            IReadOnlyList<CPlane> planes,
            IReadOnlyList<ClipMaterial> materials,
            IReadOnlyList<ushort> glassPieceIndices)
    {
        ArgumentNullException.ThrowIfNull(brushEdges);
        ArgumentNullException.ThrowIfNull(planes);
        ArgumentNullException.ThrowIfNull(materials);
        ArgumentNullException.ThrowIfNull(glassPieceIndices);

        int brushCount = GetElementCount(diskBrushes, DiskBrushSize, "collision brush");
        int diskSideCount = GetElementCount(
            diskBrushSides,
            DiskBrushSideSize,
            "collision brush side");
        int axialSideCount = checked(brushCount * 6);
        if (diskSideEdgeCounts.Length != diskSideCount)
        {
            throw new InvalidDataException(
                $"The brush-side table has {diskSideCount} rows, but the edge-count lump has {diskSideEdgeCounts.Length} bytes.");
        }
        if (diskSideCount < axialSideCount)
        {
            throw new InvalidDataException(
                $"The brush-side table has {diskSideCount} rows; {brushCount} brushes require at least {brushCount * 6} axial sides.");
        }
        if (glassPieceIndices.Count != brushCount)
        {
            throw new InvalidDataException(
                $"The glass-piece index table has {glassPieceIndices.Count} rows; expected {brushCount}.");
        }

        var rootSides = new CBrushSide[diskSideCount - axialSideCount];
        var brushes = new CBrush[brushCount];
        var bounds = new Bounds[brushCount];
        var contents = new uint[brushCount];
        int diskSideIndex = 0;
        int rootSideIndex = 0;
        int edgeIndex = 0;
        for (int brushIndex = 0; brushIndex < brushCount; brushIndex++)
        {
            ReadOnlySpan<byte> brushRow = diskBrushes.Slice(
                brushIndex * DiskBrushSize,
                DiskBrushSize);
            int diskNumSides = BinaryPrimitives.ReadInt16LittleEndian(brushRow);
            if (diskNumSides < 6 || diskSideIndex > diskSideCount - diskNumSides)
            {
                throw new InvalidDataException(
                    $"Collision brush row {brushIndex} declares invalid side count {diskNumSides}.");
            }

            int brushMaterial = BinaryPrimitives.ReadInt16LittleEndian(brushRow[2..]);
            ValidateMaterialIndex(brushMaterial, materials.Count, $"Collision brush row {brushIndex}");

            var mins = new float[3];
            var maxs = new float[3];
            var axialMaterials = new short[6];
            var axialOffsets = new byte[6];
            var axialEdgeCounts = new byte[6];
            int brushEdgeStart = edgeIndex;
            int brushEdgeOffset = 0;
            for (int axis = 0; axis < 3; axis++)
            {
                for (int direction = 0; direction < 2; direction++)
                {
                    ReadOnlySpan<byte> sideRow = diskBrushSides.Slice(
                        diskSideIndex * DiskBrushSideSize,
                        DiskBrushSideSize);
                    float bound = ReadSingle(sideRow, 0);
                    if (direction == 0)
                        mins[axis] = bound;
                    else
                        maxs[axis] = bound;

                    int materialIndex = BinaryPrimitives.ReadInt32LittleEndian(sideRow[4..]);
                    ValidateMaterialIndex(
                        materialIndex,
                        materials.Count,
                        $"Collision brush row {brushIndex} axial side {axis * 2 + direction}");
                    if (materialIndex > short.MaxValue)
                    {
                        throw new InvalidDataException(
                            $"Collision brush row {brushIndex} axial material {materialIndex} exceeds the IW4 short range.");
                    }

                    int outputIndex = axis + direction * 3;
                    axialMaterials[outputIndex] = (short)materialIndex;
                    axialOffsets[outputIndex] = ToByteOffset(
                        brushEdgeOffset,
                        brushIndex,
                        $"axial side {axis * 2 + direction}");
                    byte edgeCount = diskSideEdgeCounts[diskSideIndex];
                    axialEdgeCounts[outputIndex] = edgeCount;
                    AdvanceEdges(brushEdges.Count, edgeCount, brushIndex, ref edgeIndex, ref brushEdgeOffset);
                    diskSideIndex++;
                }
            }

            int numSides = diskNumSides - 6;
            var brushSides = new CBrushSide[numSides];
            for (int sideIndex = 0; sideIndex < brushSides.Length; sideIndex++)
            {
                ReadOnlySpan<byte> sideRow = diskBrushSides.Slice(
                    diskSideIndex * DiskBrushSideSize,
                    DiskBrushSideSize);
                int planeIndex = BinaryPrimitives.ReadInt32LittleEndian(sideRow);
                if ((uint)planeIndex >= (uint)planes.Count)
                {
                    throw new InvalidDataException(
                        $"Collision brush row {brushIndex} side {sideIndex} references plane {planeIndex}; the plane table has {planes.Count} rows.");
                }

                int materialIndex = BinaryPrimitives.ReadInt32LittleEndian(sideRow[4..]);
                ValidateMaterialIndex(
                    materialIndex,
                    materials.Count,
                    $"Collision brush row {brushIndex} side {sideIndex}");
                if (materialIndex > ushort.MaxValue)
                {
                    throw new InvalidDataException(
                        $"Collision brush row {brushIndex} side {sideIndex} material {materialIndex} exceeds the IW4 ushort range.");
                }

                byte edgeCount = diskSideEdgeCounts[diskSideIndex];
                var side = new CBrushSide
                {
                    Plane = planes[planeIndex],
                    MaterialNum = (ushort)materialIndex,
                    FirstAdjacentSideOffset = ToByteOffset(
                        brushEdgeOffset,
                        brushIndex,
                        $"side {sideIndex}"),
                    EdgeCount = edgeCount
                };
                brushSides[sideIndex] = side;
                rootSides[rootSideIndex++] = side;
                AdvanceEdges(brushEdges.Count, edgeCount, brushIndex, ref edgeIndex, ref brushEdgeOffset);
                diskSideIndex++;
            }

            var adjacentSides = new byte[brushEdgeOffset];
            for (int index = 0; index < adjacentSides.Length; index++)
                adjacentSides[index] = brushEdges[brushEdgeStart + index];

            if (numSides > ushort.MaxValue)
            {
                throw new InvalidDataException(
                    $"Collision brush row {brushIndex} has {numSides} non-axial sides; IW4 supports at most {ushort.MaxValue}.");
            }

            brushes[brushIndex] = new CBrush
            {
                NumSides = (ushort)numSides,
                GlassPieceIndex = glassPieceIndices[brushIndex],
                Sides = Array.AsReadOnly(brushSides),
                BaseAdjacentSide = Array.AsReadOnly(adjacentSides),
                AxialMaterialNum = Array.AsReadOnly(axialMaterials),
                FirstAdjacentSideOffsets = Array.AsReadOnly(axialOffsets),
                EdgeCount = Array.AsReadOnly(axialEdgeCounts)
            };
            bounds[brushIndex] = DecodeBounds(mins, maxs);
            contents[brushIndex] = unchecked((uint)materials[brushMaterial].Contents);
        }

        if (diskSideIndex != diskSideCount || rootSideIndex != rootSides.Length)
        {
            throw new InvalidDataException(
                $"Collision brushes consumed {diskSideIndex} of {diskSideCount} disk sides.");
        }
        if (edgeIndex != brushEdges.Count)
        {
            throw new InvalidDataException(
                $"Collision brushes consumed {edgeIndex} of {brushEdges.Count} adjacency bytes.");
        }

        return (
            Array.AsReadOnly(rootSides),
            Array.AsReadOnly(brushes),
            Array.AsReadOnly(bounds),
            Array.AsReadOnly(contents));
    }

    public static IReadOnlyList<ushort> DecodeLeafBrushes(ReadOnlySpan<byte> data)
    {
        int count = GetElementCount(data, DiskLeafBrushSize, "leaf brush");
        var leafBrushes = new ushort[count];
        for (int index = 0; index < leafBrushes.Length; index++)
        {
            uint brushIndex = BinaryPrimitives.ReadUInt32LittleEndian(
                data.Slice(index * DiskLeafBrushSize, DiskLeafBrushSize));
            if (brushIndex > ushort.MaxValue)
            {
                throw new InvalidDataException(
                    $"Leaf brush row {index} references brush {brushIndex}, which exceeds the IW4 ushort range.");
            }

            leafBrushes[index] = (ushort)brushIndex;
        }

        return Array.AsReadOnly(leafBrushes);
    }

