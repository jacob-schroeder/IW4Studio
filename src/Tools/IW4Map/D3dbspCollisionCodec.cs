    {
        int count = GetElementCount(data, DiskLeafSurfaceSize, "leaf surface");
        var leafSurfaces = new uint[count];
        for (int index = 0; index < leafSurfaces.Length; index++)
        {
            leafSurfaces[index] = BinaryPrimitives.ReadUInt32LittleEndian(
                data.Slice(index * DiskLeafSurfaceSize, DiskLeafSurfaceSize));
        }

        return Array.AsReadOnly(leafSurfaces);
    }

    public static IReadOnlyList<Vec3> DecodeCollisionVerts(ReadOnlySpan<byte> data)
    {
        int count = GetElementCount(data, DiskCollisionVertSize, "collision vertex");
        var verts = new Vec3[count];
        for (int index = 0; index < verts.Length; index++)
        {
            verts[index] = ReadVec3(
                data.Slice(index * DiskCollisionVertSize, DiskCollisionVertSize),
                0);
        }

        return Array.AsReadOnly(verts);
    }

    public static IReadOnlyList<ushort> DecodeCollisionTris(ReadOnlySpan<byte> data)
    {
        int count = GetElementCount(data, DiskCollisionIndexSize, "collision triangle index");
        if (count % 3 != 0)
        {
            throw new InvalidDataException(
                $"Collision triangle index count {count} is not divisible by 3.");
        }

        var triIndices = new ushort[count];
        for (int index = 0; index < triIndices.Length; index++)
        {
            triIndices[index] = BinaryPrimitives.ReadUInt16LittleEndian(
                data.Slice(index * DiskCollisionIndexSize, DiskCollisionIndexSize));
        }

        return Array.AsReadOnly(triIndices);
    }

